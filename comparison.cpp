#include <iostream>

int main() {
	int age = 25;

	std::cout << (age == 25) << std::endl;

	std::cout << (age != 25) << std::endl;

	std::cout << (age > 18) << std::endl;

	std::cout << (age < 18) << std::endl;

	std::cout << (age >= 25) << std::endl;

	std::cout << (age <= 20) << std::endl;

	return 0;
}
